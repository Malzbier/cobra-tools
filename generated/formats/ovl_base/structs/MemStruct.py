DEPENDENCY_TAG = "dependency"


from generated.base_struct import BaseStruct


class MemStruct(BaseStruct):

	"""
	this is a struct that is capable of having pointers
	"""

	__name__ = 'MemStruct'


	def __init__(self, context, arg=0, template=None, set_default=True):
		super().__init__(context, arg, template, set_default=False)
		if set_default:
			self.set_defaults()

	@classmethod
	def _get_attribute_list(cls):
		yield from super()._get_attribute_list()

	@classmethod
	def _get_filtered_attribute_list(cls, instance, include_abstract=True):
		yield from super()._get_filtered_attribute_list(instance, include_abstract)

	@classmethod
	def is_array_count(cls, f_name, set_fields):
		# logging.info(f"Checking for {f_name}")
		count_markers = ("_count", "num_")
		if check_any(count_markers, f_name):
			# logging.info(f"Found count {f_name}")
			array_name = f_name
			for c in count_markers:
				array_name = array_name.replace(c, "")
			if array_name in set_fields:
				# logging.info(f"Found array {array_name}")
				return array_name

	@classmethod
	def _from_xml(cls, instance, elem):
		"""Sets the data from the XML to this struct"""
		set_fields = cls.get_field_names(instance)
		# go over all (active through conditions) fields of this struct
		# read everything that isn't a pointer to ensure that pointer arguments are valid in the second loop
		for f_name, f_type, arguments, (optional, default) in cls._get_filtered_attribute_list(instance):
			if not issubclass(f_type, Pointer):
				# skip dummy properties
				if f_name in SKIPS:
					continue
				# keep clean XML
				if f_name.startswith(DO_NOT_SERIALIZE) or (optional and not elem.attrib.get(f_name)):
					continue
				array_name = cls.is_array_count(f_name, set_fields)
				# find the xml subelem
				if array_name:
					array = elem.find(f'./{array_name}')
					if array is not None and array.get("refcount") is not None:
						# an ALIASED ArrayPointer has no children to count, so the
						# count travels on the ref element itself
						setattr(instance, f_name, int(array.get("refcount")))
					elif array:
						# handle arrays that are nested in a wrapper, so look there for their count
						child = array.find(f'./ptrs')
						if child:
							array = child
						setattr(instance, f_name, len(array))
					elif elem.attrib.get(f_name):
						# non-zero count with a NULL array pointer, preserved by
						# _to_xml because the derivation below cannot express it
						setattr(instance, f_name, int(elem.attrib[f_name]))
					else:
						setattr(instance, f_name, 0)
				else:
					setattr(instance, f_name, f_type.from_xml(instance, elem, f_name, *arguments))

		# finally read the pointers
		for f_name, f_type, arguments, (optional, default) in cls._get_filtered_attribute_list(instance):
			if issubclass(f_type, Pointer):
				arg, template = arguments
				if template is None:
					# A pointer declared without a template gets one from
					# get_ptr_template(), exactly as read_ptrs does on the BINARY
					# path. Without this the XML path leaves data=None, _to_xml
					# emits nothing, and write_ptr_all then drops the relocation
					# AND its whole target block, including everything nested
					# inside it. Polymorphic pointers (Activity.data,
					# MRFMember1.ptr_0) are precisely the ones declared this way,
					# so the asymmetry silently deleted the most interesting data
					template = instance.get_ptr_template(f_name)
				setattr(instance, f_name, f_type.from_xml(instance, elem, f_name, arg, template))

		# also add any meta-data that is not directly part of the struct generated by the codegen
		for attr, value in elem.attrib.items():
			if attr not in set_fields:
				# logging.debug(f"Adding string metadata '{attr} = {value}' from XML element '{elem.tag}'")
				setattr(instance, attr, value)
		return instance

	def write_ptrs(self, loader, pool):
		"""Process all pointers in the structure and recursively load pointers in the sub-structs."""
		# recursive doesnt get the whole structure - why?
		# could work if the order is good
		if self.io_start not in pool.offsets:
			# An ArrayPointer targets ELEMENT 0 ONLY - elements 1..n-1 are not
			# relocation targets - so the whole array is ONE block and
			# calc_size_map sizes it as n x unit. Writing the array contiguously
			# is correct, but registering EVERY member's own offset below makes
			# calc_size_map split that single block back into n on the next load
			# A struct that starts INSIDE an already-registered block of the same
			# pool is therefore an array TAIL element: its pointers are real
			# relocations and must still be emitted, but it must not become a
			# block of its own
			for o in pool.offsets:
				sz = pool.size_map.get(o)
				if sz and o < self.io_start < o + sz:
					children = loader.stack.setdefault((pool, o), {})
					for ptr, f_name, arguments in MemStruct.get_instances_recursive(self, Pointer):
						# retail treats an EMPTY pointer differently here - see
						# Pointer.write_ptr. Recorded on the pointer because
						# write_ptr has no access to the owning struct and its
						# signature must not change (LookupPointer and Reference
						# override it)
						ptr.in_array_tail = True
						ptr.write_ptr_all(self, children, f_name, loader, pool)
					return
		pool.offsets.add(self.io_start)
		# NEVER SHRINK an already-recorded block. Pointer.write_ptr registers an
		# array's block as its FULL written extent, but element 0 starts exactly
		# where the array does, so it reaches here (the loop above needs io_start
		# strictly INSIDE) and used to overwrite that extent with ONE element's
		# io_size. Every element after it then failed the same containment test and
		# registered as a block of its own - defeating the array-tail handling above
		# entirely. Measured on WTR_WaterPump/models.ms2: write_ptrs saw both
		# ModelInfos as block starts and never once took the tail branch, and every
		# CHANGED .ms2 entry in the PC2 sample carried the resulting extra block as
		# a +1 reachable-struct count against retail
		pool.size_map[self.io_start] = max(pool.size_map.get(self.io_start, 0), self.io_size)
		children = loader.stack[(pool, self.io_start)] = {}
		for ptr, f_name, arguments in MemStruct.get_instances_recursive(self, Pointer):
			ptr.in_array_tail = False
			ptr.write_ptr_all(self, children, f_name, loader, pool)

	@classmethod
	def get_all_str_pointers(cls, instance):
		for ptr, f_name, arguments in MemStruct.get_instances_recursive(instance, Pointer):
			if ptr.template and issubclass(ptr.template, ZString):
				yield ptr  # , f_name, arguments
			elif isinstance(ptr.data, MemStruct):
				yield from MemStruct.get_all_str_pointers(ptr.data)
			elif isinstance(ptr.data, Array):
				for elem in ptr.data:
					if isinstance(elem, MemStruct):
						yield from MemStruct.get_all_str_pointers(elem)

	@classmethod
	def get_instances_recursive(cls, instance, dtype):
		for s_type, s_inst, (f_name, f_type, arguments, _) in cls.get_condition_attributes_recursive(instance, instance, lambda x: issubclass(x[1], dtype)):
			f_inst = s_type.get_field(s_inst, f_name)
			yield f_inst, f_name, arguments

	def read_ptrs(self, pool, debug=False):
		"""Process all pointers in the structure and recursively load pointers in the sub-structs."""
		offsets_of_ptrs = set()
		# need to recurse here, because we may have substructs that are part of this MemStruct (not via ptrs)
		for ptr, f_name, arguments in MemStruct.get_instances_recursive(self, Pointer):
			# update the pointer's arg, as it is sometimes read after the pointer
			ptr.arg, template = arguments
			if not ptr.template:
				# try the lookup function to get a suitable template for this field
				ptr.template = self.get_ptr_template(f_name)
			offsets_of_ptrs.add(ptr.io_start)
			# locates the read address, attaches the frag entry, and reads the template as ptr.data
			ptr.read_ptr(pool)
			if ptr.target_pool:
				# keep reading pointers in the newly read ptr.data
				for memstruct in self.structs_from_ptr(ptr):
					memstruct.read_ptrs(ptr.target_pool, debug=debug)
		if debug:
			# verify that there is no uncaught pointer
			for l_offset, rel_offset, entry in pool.get_ptrs_in_struct(self.io_start, self.io_size):
				# skip dependencies
				if isinstance(entry, tuple):
					target_pool, target_offset = entry
					if l_offset not in offsets_of_ptrs:
						logging.warning(f"Pointer at {pool.i} | {l_offset} to {target_pool.i} | {target_offset} is missing for {self.__class__.__name__} (rel offset: {rel_offset})")

	@staticmethod
	def structs_from_ptr(ptr):
		"""Get all direct memstruct children of this ptr"""
		if isinstance(ptr.data, MemStruct):
			yield ptr.data
		elif isinstance(ptr.data, Array):
			# NOTE: no assert on the pointer class. A plain Pointer can hold an
			# Array when the element count came from the BLOCK SIZE rather than
			# from a count field (see Pointer.infer_array); iteration here is
			# type-agnostic anyway, and the assert was the only thing that cared
			for member in ptr.data:
				if isinstance(member, MemStruct):
					yield member
		# A typed TAIL sharing the owner's block (see Pointer.read_block_tail) is
		# not a declared field, so get_instances_recursive would never reach its
		# pointers and their relocations would be dropped - which is exactly the
		# loss the tail mechanism exists to prevent
		for member in getattr(ptr, "tail_data", None) or ():
			if isinstance(member, MemStruct):
				yield member

	@classmethod
	def _to_xml(cls, instance, elem, debug):
		"""Assigns data self to xml elem"""
		super()._to_xml(instance, elem, debug)
		# A COUNT can be non-zero while its ARRAY POINTER IS NULL, and the XML
		# has no way to say so. BaseStruct._to_xml skips array-count fields
		# outright because _from_xml re-derives them as len(<array element>)
		# That works while the two agree, but a struct can genuinely carry a
		# count with a null array pointer - no pointer means no element, so the
		# count re-derives as 0 and a retail 1 or 3 comes back 0
		# Emit the count only in the case the derivation cannot cover, so XML
		# that round-trips today is unchanged
		set_fields = cls.get_field_names(instance)
		for f_name, f_type, arguments, (optional, default) in cls._get_filtered_attribute_list(instance):
			array_name = cls.is_array_count(f_name, set_fields)
			if not array_name or elem.find(f'./{array_name}') is not None:
				continue
			try:
				val = int(getattr(instance, f_name, 0) or 0)
			except (TypeError, ValueError):
				continue
			if val:
				elem.set(f_name, str(val))

	def get_ptr_template(self, prop):
		"""Returns the appropriate template for a pointer named 'prop', if exists.
		Must be overwritten in subclass"""
		return None


